"""Write PX4 SITL airframe files for the three ResQMesh roles (based on PX4's 4001_gz_x500)."""
import json
import math
import os

import yaml

SIM = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
geo = json.load(open(os.path.join(SIM, 'cad_export', 'geometry.json')))
mp = json.load(open(os.path.join(SIM, 'config', 'mass_props.json')))
P = yaml.safe_load(open(os.path.join(SIM, 'config', 'vehicle_params.yaml')))['propulsion']
OUT = os.path.join(SIM, 'px4', 'airframes')
os.makedirs(OUT, exist_ok=True)
IDS = {'scout': 4560, 'mapper': 4561, 'relay': 4562}

X500 = {'arm': math.hypot(0.174, 0.174), 'ixx': 0.02166666, 'izz': 0.04}
DEF = {'MC_ROLLRATE_P': 0.15, 'MC_ROLLRATE_I': 0.2, 'MC_ROLLRATE_D': 0.003,
       'MC_PITCHRATE_P': 0.15, 'MC_PITCHRATE_I': 0.2, 'MC_PITCHRATE_D': 0.003,
       'MC_YAWRATE_P': 0.2, 'MC_YAWRATE_I': 0.1}

ax = abs(geo['motor_xy_m']['motor_1'][0])
ay = abs(geo['motor_xy_m']['motor_1'][1])
arm = math.hypot(ax, ay)
w_min, w_max = 150.0, 1000.0

for role, aid in IDS.items():
    m = mp[role]
    ixx, izz = m['inertia']['ixx'], m['inertia']['izz']
    k_rp = (arm / ixx) / (X500['arm'] / X500['ixx'])
    k_y = (1 / izz) / (1 / X500['izz'])
    gains = {k: v / (k_y if k.startswith('MC_YAW') else k_rp) for k, v in DEF.items()}
    # hover command: thrust = motor_constant * w^2, w = w_min + u (w_max - w_min)
    w_h = math.sqrt(m['mass_kg'] * 9.81 / 4 / P['motor_constant'])
    thr_hover = (w_h - w_min) / (w_max - w_min)
    lines = ['#!/bin/sh', '#', '# @name ResQMesh %s (Gazebo)' % role.capitalize(), '#', '# @type Quadrotor', '#',
             '# Generated by sim/tools/gen_airframes.py. Masses behind these numbers are placeholders.', '#', '',
             '. ${R}etc/init.d/rc.mc_defaults', '',
             'PX4_SIMULATOR=${PX4_SIMULATOR:=gz}', 'PX4_GZ_WORLD=${PX4_GZ_WORLD:=resqmesh_landslide}',
             'PX4_SIM_MODEL=${PX4_SIM_MODEL:=resqmesh_%s}' % role, '',
             'param set-default SIM_GZ_EN 1', '', 'param set-default CA_AIRFRAME 0', 'param set-default CA_ROTOR_COUNT 4']
    for i, (px, py, km) in enumerate(((ax, ay, 0.05), (-ax, -ay, 0.05), (ax, -ay, -0.05), (-ax, ay, -0.05))):
        lines += ['param set-default CA_ROTOR%d_PX %.4f' % (i, px), 'param set-default CA_ROTOR%d_PY %.4f' % (i, py),
                  'param set-default CA_ROTOR%d_KM %.2f' % (i, km)]
    for i in range(1, 5):
        lines += ['param set-default SIM_GZ_EC_FUNC%d %d' % (i, 100 + i), 'param set-default SIM_GZ_EC_MIN%d %d' % (i, w_min),
                  'param set-default SIM_GZ_EC_MAX%d %d' % (i, w_max)]
    lines += ['', '# hover thrust from mass %.3f kg (placeholder); the PX4 hover-thrust estimator refines it in flight' % m['mass_kg'],
              'param set-default MPC_THR_HOVER %.2f' % thr_hover, '',
              '# rate gains: PX4 defaults scaled by control authority vs x500 (roll/pitch /%.1f, yaw /%.1f)' % (k_rp, k_y)]
    lines += ['param set-default %s %.4f' % (k, v) for k, v in gains.items()]
    lines += ['', '# mission behaviour: offboard, generous limits for a 5-inch frame',
              'param set-default MPC_XY_VEL_MAX 12', 'param set-default MPC_Z_VEL_MAX_UP 4', 'param set-default MPC_TILTMAX_AIR 35',
              '# yaw: a low-inertia frame saturates its mixer on a big heading step, so turn gently',
              'param set-default MC_YAW_P 2.0', 'param set-default MC_YAWRATE_MAX 60', 'param set-default MPC_YAWRAUTO_MAX 45',
              'param set-default COM_OF_LOSS_T 2', 'param set-default COM_OBL_RC_ACT 4', 'param set-default NAV_DLL_ACT 0',
              'param set-default NAV_RCL_ACT 0', 'param set-default COM_RCL_EXCEPT 4', 'param set-default COM_ARM_WO_GPS 0',
              'param set-default SIM_BAT_DRAIN 7200', 'param set-default SIM_BAT_MIN_PCT 70', 'param set-default COM_LOW_BAT_ACT 0',
              'param set-default EKF2_BCOEF_X 0.0', 'param set-default EKF2_BCOEF_Y 0.0', 'param set-default EKF2_MCOEF 0.12', '']
    p = os.path.join(OUT, '%d_gz_resqmesh_%s' % (aid, role))
    open(p, 'w', newline='\n').write('\n'.join(lines))
    print(os.path.basename(p), 'hover %.2f  roll/pitch /%.1f  yaw /%.1f' % (thr_hover, k_rp, k_y))

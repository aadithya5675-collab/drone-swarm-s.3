"""Textured visuals for the landslide debris (the flat-coloured STL look is replaced by wet mud, rock and wood)."""
import glob
import os
import re
import struct

import numpy as np
from PIL import Image
from scipy import ndimage

SIM = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MOD = os.path.join(SIM, 'models')
TEX = os.path.join(MOD, 'resqmesh_textures', 'materials', 'textures')
N = 1024
TILE_M = {'mud': 16.0, 'mud_wet': 16.0, 'rock': 2.5, 'log': 2.0, 'rubble': 3.0}
rng = np.random.default_rng(42)


def noise(sigma, n=N):
    a = ndimage.gaussian_filter(rng.standard_normal((n, n)), sigma, mode='wrap')   # 'wrap' keeps it tileable
    return (a - a.mean()) / (a.std() + 1e-9)


def fbm(sigmas, weights):
    return sum(w * noise(s) for s, w in zip(sigmas, weights)) / sum(weights)


def normal_map(h, strength):
    gy, gx = np.gradient(h)
    nx, ny, nz = -gx * strength, -gy * strength, np.ones_like(h)
    L = np.sqrt(nx * nx + ny * ny + nz * nz)
    return (np.dstack([nx / L, ny / L, nz / L]) * 0.5 + 0.5)


def save(name, rgb):
    Image.fromarray((np.clip(rgb, 0, 1) * 255).astype(np.uint8)).save(os.path.join(TEX, name))


def textures():
    os.makedirs(TEX, exist_ok=True)
    open(os.path.join(MOD, 'resqmesh_textures', 'model.config'), 'w').write(
        '<?xml version="1.0"?><model><name>resqmesh_textures</name><version>1.0</version><sdf version="1.9">model.sdf</sdf>'
        '<author><name>Team Apex (generated)</name></author></model>\n')
    open(os.path.join(MOD, 'resqmesh_textures', 'model.sdf'), 'w').write(
        '<?xml version="1.0"?><sdf version="1.9"><model name="resqmesh_textures"><static>true</static><link name="l"/></model></sdf>\n')
    # wet mud: large damp patches, flow streaks along v, gravel specks
    big, mid, fine = noise(60), noise(14), noise(2.5)
    streak = ndimage.gaussian_filter(rng.standard_normal((N, N)), (26, 9), mode='wrap')
    streak = (streak - streak.mean()) / streak.std()
    wet = np.clip(0.42 + 0.30 * big + 0.10 * streak, 0, 1)
    base = np.array([0.50, 0.39, 0.27])
    dark = np.array([0.31, 0.23, 0.15])
    col = base[None, None] * (1 - wet[..., None]) + dark[None, None] * wet[..., None]
    col *= (1 + 0.12 * mid[..., None] + 0.07 * fine[..., None])
    specks = fine > 2.2
    col[specks] = np.array([0.52, 0.49, 0.45]) * (1 + 0.1 * mid[specks])[:, None]
    save('mud_albedo.png', col)
    h = 0.6 * mid + 0.4 * fine + 1.2 * specks
    save('mud_normal.png', normal_map(ndimage.gaussian_filter(h, 1, mode='wrap'), 2.2))
    save('mud_wet_albedo.png', col * 0.78)
    # rock: grey granite-gneiss with veins
    r1, r2, r3 = noise(20), noise(5), noise(1.5)
    vein = np.abs(noise(8)) < 0.08
    g = 0.46 + 0.07 * r1 + 0.05 * r2 + 0.04 * r3
    col = np.dstack([g, g * 0.97, g * 0.92])
    col[vein] *= 1.25
    save('rock_albedo.png', col)
    save('rock_normal.png', normal_map(0.5 * r2 + 0.5 * r3, 3.0))
    # wood (snapped trunks): bark along u
    bark = ndimage.gaussian_filter(rng.standard_normal((N, N)), (1.5, 30), mode='wrap')
    bark = (bark - bark.mean()) / bark.std()
    w = 0.30 + 0.06 * bark + 0.03 * noise(3)
    save('log_albedo.png', np.dstack([w, w * 0.75, w * 0.52]))
    save('log_normal.png', normal_map(bark, 2.5))
    # concrete/brick rubble of collapsed houses
    c1, c2 = noise(10), noise(2)
    g = 0.50 + 0.06 * c1 + 0.05 * c2
    col = np.dstack([g * 1.02, g * 0.96, g * 0.90])
    brick = noise(6) > 1.0
    col[brick] = np.array([0.55, 0.33, 0.24]) * (1 + 0.08 * c2[brick])[:, None]
    save('rubble_albedo.png', col)
    save('rubble_normal.png', normal_map(0.6 * c1 + 0.4 * c2 + 0.8 * brick, 2.5))


def read_stl(p):
    b = open(p, 'rb').read()
    n = struct.unpack('<I', b[80:84])[0]
    a = np.frombuffer(b[84:84 + n * 50], dtype=np.dtype([('n', '<3f4'), ('v', '<9f4'), ('a', '<u2')]))
    return a['v'].reshape(-1, 3, 3).astype(np.float64)


def write_obj(p, tris, tile, planar='xy'):
    v = tris.reshape(-1, 3)
    e1, e2 = tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0]
    nrm = np.cross(e1, e2)
    nrm /= np.maximum(np.linalg.norm(nrm, axis=1, keepdims=True), 1e-12)
    if planar == 'tri':
        ax = np.abs(nrm).argmax(1).repeat(3)
        uv = np.where(ax[:, None] == 0, v[:, [1, 2]], np.where(ax[:, None] == 1, v[:, [0, 2]], v[:, [0, 1]])) / tile
    else:
        uv = v[:, :2] / tile
    with open(p, 'w') as f:
        f.write('# generated by tools/texture_scene.py\n')
        f.write(''.join('v %.3f %.3f %.3f\n' % tuple(q) for q in v))
        f.write(''.join('vt %.4f %.4f\n' % tuple(q) for q in uv))
        f.write(''.join('vn %.4f %.4f %.4f\n' % tuple(q) for q in nrm))
        f.write(''.join('f %d/%d/%d %d/%d/%d %d/%d/%d\n' % (3 * i + 1, 3 * i + 1, i + 1, 3 * i + 2, 3 * i + 2, i + 1, 3 * i + 3, 3 * i + 3, i + 1)
                        for i in range(len(tris))))


def pbr(tex, rough):
    t = 'model://resqmesh_textures/materials/textures/'
    alb = t + ('mud_wet' if tex == 'mud_wet' else tex) + '_albedo.png'
    nm = t + ('mud' if tex == 'mud_wet' else tex) + '_normal.png'
    return ('<material><ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><specular>0.12 0.12 0.12 1</specular><pbr><metal>'
            '<albedo_map>%s</albedo_map><normal_map>%s</normal_map><roughness>%.2f</roughness><metalness>0.0</metalness>'
            '</metal></pbr></material>' % (alb, nm, rough))


KIND = {'mud': ('mud', 0.9, 'xy'), 'mud_wet': ('mud_wet', 0.55, 'xy'), 'rock': ('rock', 0.8, 'tri'),
        'log': ('log', 0.85, 'tri'), 'rubble': ('rubble', 0.9, 'tri')}


def retexture(model_dir):
    p = os.path.join(model_dir, 'model.sdf')
    s = open(p).read()
    name = os.path.basename(model_dir)
    n = 0
    for vis in re.findall(r'<visual name="([^"]+)">', s):
        if vis not in KIND:
            continue
        stl = os.path.join(model_dir, 'meshes', vis + '.stl')
        if not os.path.exists(stl):
            continue
        tex, rough, planar = KIND[vis]
        write_obj(os.path.join(model_dir, 'meshes', vis + '.obj'), read_stl(stl), TILE_M[vis], planar)
        pat = re.compile(r'<visual name="%s">.*?</visual>' % re.escape(vis), re.S)
        new = '<visual name="%s"><geometry><mesh><uri>model://%s/meshes/%s.obj</uri></mesh></geometry>%s</visual>' % (
            vis, name, vis, pbr(tex, rough))
        s = pat.sub(new, s, count=1)
        n += 1
    open(p, 'w', newline='\n').write(s)
    return n


def main():
    textures()
    total = 0
    for d in sorted(glob.glob(os.path.join(MOD, 'resqmesh_debris_*')) + glob.glob(os.path.join(MOD, 'resqmesh_collapsed_*'))):
        total += retexture(d)
    print('textures written; %d visuals retextured' % total)


if __name__ == '__main__':
    main()
